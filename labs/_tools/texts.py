def chart1_svg(rows, facts) -> str:
    x0, x1, y0, y1 = 90, 720, 400, 110  # plot box: internet 0..100, life 50..90

    def px(v):
        return x0 + (x1 - x0) * v / 100

    def py(v):
        return y0 + (y1 - y0) * (v - 50) / 40

    xs, ys = [r["net"] for r in rows], [r["life"] for r in rows]
    n = len(rows)
    mx, my = sum(xs) / n, sum(ys) / n
    b = sum((x - mx) * (y - my) for x, y in zip(xs, ys)) / sum((x - mx) ** 2 for x in xs)
    a = my - b * mx
    dots = "".join(f'<circle cx="{px(r["net"]):.1f}" cy="{py(r["life"]):.1f}" r="6" fill="#0f766e" fill-opacity="0.75"/>' for r in rows)
    labels = ""
    for iso, dx, dy in (("SAU", 0, -12), ("JPN", 0, -12), ("NGA", 0, 22), ("ETH", 0, -12), ("BGD", 0, -12), ("ZAF", 0, 22)):
        r = next(r for r in rows if r["iso3"] == iso)
        labels += f'<text x="{px(r["net"]) + dx:.1f}" y="{py(r["life"]) + dy:.1f}" text-anchor="middle" font-size="13" fill="#334155">{r["country_ar"]}</text>'
    ticks = "".join(f'<text x="{px(v):.0f}" y="424" text-anchor="middle" font-size="13" fill="#475569">{v}%</text>' for v in (0, 25, 50, 75, 100))
